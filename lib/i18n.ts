/**
 * Every sentence the app shows, in English and Polish. Polish uses the real plural forms
 * (1 dzień, 2 dni, 5 dni, 22 dni) and stays impersonal, so it fits any reader.
 */
type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => Widen<R>
  : T extends string
    ? string
    : T extends readonly (infer U)[]
      ? Widen<U>[]
      : T extends object
        ? { [K in keyof T]: Widen<T[K]> }
        : T;

/** English literals widened so the Polish copy can use its own wording. */
export type Copy = Widen<ReturnType<typeof english>>;

export function copy(lang: Lang): Copy {
  return lang === "pl" ? polish() : english();
}

export function useCopy() {
  const lang: Lang = useGoReal()?.lang === "pl" ? "pl" : "en";
  return { lang, c: copy(lang), setLang };
}

export function weekLetters(lang: Lang, mondayFirst: boolean): string[] {
  const fromSunday = lang === "pl" ? ["N", "Pn", "Wt", "Śr", "Cz", "Pt", "So"] : ["S", "M", "T", "W", "T", "F", "S"];
  if (!mondayFirst) return fromSunday;
  return lang === "pl" ? ["Pn", "Wt", "Śr", "Cz", "Pt", "So", "N"] : ["M", "T", "W", "T", "F", "S", "S"];
}

