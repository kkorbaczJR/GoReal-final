export type PixelIconName = keyof typeof ICONS;

const COLORS: Record<string, string> = {
  "#": "currentColor",
  o: "var(--accent)",
  w: "#ffffff",
  g: "#d4d4d4",
};

export function PixelIcon({
  name,
  size = 24,
  dim = false,
  className,
  viewBox = "0 0 12 12",
  stretch = false,
}: {
  name: PixelIconName;
  size?: number;
  /** Gray version (e.g. an unlit streak). */
  dim?: boolean;
  className?: string;
  /** Crop the 12×12 grid, e.g. to the pixels that are actually drawn. */
  viewBox?: string;
  /** Stretch the cropped pixels to `size` instead of keeping them square. */
  stretch?: boolean;
}) {
  const rows = ICONS[name];
  const rects: React.ReactNode[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x];
      if (!(c in COLORS)) continue;
      const fill = dim ? (c === "w" ? "#ffffff" : "#d4d4d4") : COLORS[c];
      rects.push(<rect key={`${x},${y}`} x={x} y={y} width={1.02} height={1.02} fill={fill} />);
    }
  });
  return (
    <svg
      width={size}
      height={size}
      viewBox={viewBox}
      preserveAspectRatio={stretch ? "none" : undefined}
      shapeRendering="crispEdges"
      aria-hidden
      className={className}
      style={{ display: "block", flexShrink: 0 }}
    >
      {rects}
    </svg>
  );
}
